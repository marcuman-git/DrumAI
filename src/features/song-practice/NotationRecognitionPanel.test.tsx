it('reuses unchanged staff analysis but invalidates it when threshold or crop changes', () => {
  vi.spyOn(HTMLCanvasElement.prototype, 'getContext').mockReturnValue({ createImageData: () => ({ data: new Uint8ClampedArray(80000) }), putImageData: vi.fn(), beginPath: vi.fn(), moveTo: vi.fn(), lineTo: vi.fn(), stroke: vi.fn(), strokeRect: vi.fn() } as unknown as CanvasRenderingContext2D)
  const pixels = new Uint8ClampedArray(80000)
  const view = render(<NotationRecognitionPanel pixels={pixels} width={200} height={100} source="fixture.pdf" page={1} />)
  const scan = () => fireEvent.click(screen.getByRole('button', { name: 'Detect staffs and note candidates' }))
  scan(); scan()
  expect(screen.getByText(/staff analysis reused/)).toBeVisible()
  fireEvent.change(screen.getByLabelText('Recognition threshold'), { target: { value: '170' } })
  scan(); expect(screen.queryByText(/staff analysis reused/)).toBeNull()
  scan(); expect(screen.getByText(/staff analysis reused/)).toBeVisible()
  view.rerender(<NotationRecognitionPanel pixels={new Uint8ClampedArray(80000)} width={200} height={100} source="replacement.pdf" page={1} />)
  scan(); expect(screen.queryByText(/staff analysis reused/)).toBeNull()
})
