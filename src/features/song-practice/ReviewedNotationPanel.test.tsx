import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { ReviewedNotationPanel } from './ReviewedNotationPanel'
afterEach(cleanup)
it('requires full rhythm and explicit confirmation before passing a reviewed bar', () => {
  const onConfirm = vi.fn()
  render(<ReviewedNotationPanel notes={[]} hints={{}} first={0} last={150} image={null} staff={null} onConfirm={onConfirm} />)
  expect(screen.getByRole('button', { name: 'Confirm reviewed bar' })).toBeDisabled()
  fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
  fireEvent.change(screen.getByLabelText('Event 1 duration'), { target: { value: '4' } })
  fireEvent.click(screen.getByRole('button', { name: 'Fill gaps with manual rests' }))
  fireEvent.click(screen.getByRole('checkbox', { name: /I verified every onset/ }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm reviewed bar' }))
  expect(onConfirm.mock.calls[0][0].rhythmEvents[0].duration).toBe(4)
  fireEvent.change(screen.getByLabelText('Event 1 slot'), { target: { value: '2' } })
  expect(screen.getByRole('button', { name: 'Confirm reviewed bar' })).toBeDisabled()
})
it('jumps to an overlapping event and requires explicit re-verification after correction', () => {
 render(<ReviewedNotationPanel notes={[]} hints={{}} first={0} last={150} image={null} staff={null} onConfirm={vi.fn()} />)
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 fireEvent.change(screen.getByLabelText('Event 1 duration'), { target: { value: '4' } })
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 expect(within(screen.getByLabelText('Voice correction diagnostics')).getByText(/Overlapping slots: 1/)).toBeVisible()
 fireEvent.click(screen.getByRole('button', { name: 'Jump to event 2 (overlap)' }))
 expect(screen.getByLabelText('Event 2 slot')).toHaveFocus()
 fireEvent.change(screen.getByLabelText('Event 2 slot'), { target: { value: '5' } })
 expect(screen.queryByRole('button', { name: 'Jump to event 2 (overlap)' })).toBeNull()
 fireEvent.click(screen.getByRole('button', { name: 'Fill next gap with manual rests' }))
 expect(screen.getByText(/First gap filled with manual rests/)).toBeVisible()
 expect(screen.getByRole('button', { name: 'Confirm reviewed bar' })).toBeDisabled()
})
it('filters event rows without dropping hidden voices or changing confirmation data', () => {
 const onConfirm = vi.fn()
 render(<ReviewedNotationPanel notes={[]} hints={{}} first={0} last={150} image={null} staff={null} onConfirm={onConfirm} />)
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 fireEvent.change(screen.getByLabelText('Review instrument'), { target: { value: 'Kick' } })
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 fireEvent.click(screen.getByLabelText('Show selected review instrument only'))
 expect(screen.queryByLabelText('Event 1 slot')).toBeNull()
 expect(screen.getByLabelText('Event 2 slot')).toBeVisible()
 fireEvent.click(screen.getByLabelText('Show selected review instrument only'))
 expect(screen.getByLabelText('Event 1 slot')).toBeVisible()
 expect(onConfirm).not.toHaveBeenCalled()
})
it('points to an overflowing event and clears that warning when corrected', () => {
 render(<ReviewedNotationPanel notes={[]} hints={{}} first={0} last={150} image={null} staff={null} onConfirm={vi.fn()} />)
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 fireEvent.change(screen.getByLabelText('Event 1 duration'), { target: { value: '4' } })
 fireEvent.change(screen.getByLabelText('Event 1 slot'), { target: { value: '16' } })
 fireEvent.click(screen.getByRole('button', { name: 'Jump to event 1 (crosses bar end)' }))
 expect(screen.getByLabelText('Event 1 slot')).toHaveFocus()
 fireEvent.change(screen.getByLabelText('Event 1 slot'), { target: { value: '13' } })
 expect(screen.queryByRole('button', { name: 'Jump to event 1 (crosses bar end)' })).toBeNull()
 expect(screen.getByRole('button', { name: 'Confirm reviewed bar' })).toBeDisabled()
})
it('undoes and redoes gap fill without restoring source confirmation or sending a draft', () => {
 const onConfirm = vi.fn(); const onInvalidate = vi.fn()
 render(<ReviewedNotationPanel notes={[]} hints={{}} first={0} last={150} image={null} staff={null} onConfirm={onConfirm} onInvalidate={onInvalidate} />)
 expect(screen.getByRole('button', { name: 'Undo review edit' })).toBeDisabled()
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 fireEvent.change(screen.getByLabelText('Event 1 duration'), { target: { value: '4' } })
 fireEvent.click(screen.getByRole('button', { name: 'Fill next gap with manual rests' }))
 fireEvent.click(screen.getByRole('checkbox', { name: /I verified every onset/ }))
 fireEvent.click(screen.getByRole('button', { name: 'Confirm reviewed bar' }))
 expect(onConfirm).toHaveBeenCalledTimes(1)
 onInvalidate.mockClear()
 fireEvent.click(screen.getByRole('button', { name: 'Undo review edit' }))
 expect(screen.queryByLabelText('Event 2 slot')).toBeNull()
 expect(onInvalidate).toHaveBeenCalledTimes(1)
 fireEvent.click(screen.getByRole('button', { name: 'Redo review edit' }))
 expect(screen.getByLabelText('Event 2 slot')).toBeVisible()
 expect(screen.getByRole('checkbox', { name: /I verified every onset/ })).not.toBeChecked()
 expect(screen.getByRole('button', { name: 'Confirm reviewed bar' })).toBeDisabled()
 expect(onConfirm).toHaveBeenCalledTimes(1)
 expect(onInvalidate).toHaveBeenCalledTimes(2)
})
it('restores removed event settings and clears redo on a new edit', () => {
 render(<ReviewedNotationPanel notes={[]} hints={{}} first={0} last={150} image={null} staff={null} onConfirm={vi.fn()} />)
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 fireEvent.change(screen.getByLabelText('Event 1 instrument'), { target: { value: 'Kick' } })
 fireEvent.change(screen.getByLabelText('Event 1 slot'), { target: { value: '5' } })
 fireEvent.change(screen.getByLabelText('Event 1 duration'), { target: { value: '2' } })
 fireEvent.click(screen.getByRole('button', { name: 'Remove event 1' }))
 fireEvent.click(screen.getByRole('button', { name: 'Undo review edit' }))
 expect(screen.getByLabelText('Event 1 instrument')).toHaveValue('Kick')
 expect(screen.getByLabelText('Event 1 slot')).toHaveValue(5)
 expect(screen.getByLabelText('Event 1 duration')).toHaveValue('2')
 fireEvent.change(screen.getByLabelText('Event 1 kind'), { target: { value: 'rest' } })
 expect(screen.getByRole('button', { name: 'Redo review edit' })).toBeDisabled()
})
it('resets event history when the source review remounts', () => {
 const props = { notes: [], hints: {}, first: 0, last: 150, image: null, staff: null, onConfirm: vi.fn() }
 const view = render(<ReviewedNotationPanel key="source-a" {...props} />)
 fireEvent.click(screen.getByRole('button', { name: 'Add reviewed note' }))
 expect(screen.getByRole('button', { name: 'Undo review edit' })).toBeEnabled()
 view.rerender(<ReviewedNotationPanel key="source-b" {...props} />)
 expect(screen.getByRole('button', { name: 'Undo review edit' })).toBeDisabled()
 expect(screen.queryByLabelText('Event 1 slot')).toBeNull()
})
it('links initialized events to source candidates through edits and undo', () => {
 const onInspectCandidate = vi.fn()
 const notes = [{ id: 7, x: 0, y: 50, instrument: 'Snare' as const, shape: 'oval' as const, strength: 1, stemHint: true, flagHint: false }]
 render(<ReviewedNotationPanel notes={notes} hints={{}} first={0} last={150} image={null} staff={null} onConfirm={vi.fn()} onInspectCandidate={onInspectCandidate} />)
 fireEvent.click(screen.getByRole('button', { name: 'Initialize accepted notes' }))
 fireEvent.change(screen.getByLabelText('Event 1 instrument'), { target: { value: 'Kick' } })
 fireEvent.click(screen.getByRole('button', { name: 'Inspect source for event 1' }))
 expect(onInspectCandidate).toHaveBeenCalledWith(7)
 fireEvent.click(screen.getByRole('button', { name: 'Undo review edit' }))
 expect(screen.getByRole('button', { name: 'Inspect source for event 1' })).toBeVisible()
})
